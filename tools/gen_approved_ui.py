#!/usr/bin/env python3
"""Approved native RGB565 artwork, row-indexed RLE; no scaling or palette loss."""
from pathlib import Path
from PIL import Image
import sys
root=Path(__file__).resolve().parents[1]
ref=root/'assets/ui/approved-0995'
files=['LD','AH','LR','GC','TAPE','VHS','VINYL'];out=['/* generated by gen_approved_ui.py; approved 240px references, row-indexed RGB565 RLE */','#pragma once','#include <stdint.h>','typedef struct { const uint16_t *row; const uint32_t *run; } approved_img_t;']
total=0
for name in files:
 im=Image.open(ref/(name+'.png')).convert('RGB');assert im.size==(240,240)
 rows=[0];runs=[]
 for y in range(240):
  if y<19 or y>=179:
   rows.append(len(runs));continue
  vals=[]
  for x in range(240):
   r,g,b=im.getpixel((x,y));v=((r*31+127)//255<<11)|((g*63+127)//255<<5)|((b*31+127)//255);vals.append((v>>8)|((v&255)<<8))
  i=0
  while i<240:
   j=i+1
   while j<240 and vals[j]==vals[i]:j+=1
   runs.append(((j-i-1)<<16)|vals[i]);i=j
  rows.append(len(runs))
 assert len(runs)<65536
 out+=['static const uint16_t AP_'+name+'_row[241]={'+','.join(map(str,rows))+'};','static const uint32_t AP_'+name+'_run[]={'+','.join(hex(v) for v in runs)+'};']
 size=len(runs)*4+482;total+=size;print(name,size)
out+=['static const approved_img_t AP_IMAGES[7]={'+','.join('{AP_'+n+'_row,AP_'+n+'_run}' for n in files)+'};']
Path(sys.argv[1]).write_text('\n'.join(out)+'\n');print('Total approved assets',total)
