"""The FM6 factory bank (assets/fm6/trapstation-fm6-bank.json) as build/gen/trap_fm6_factory.h."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def unpack(b):
    """A packed 128-byte bank record as the 155 voice bytes (the check of the packing below)."""
    v = []
    for k in range(6):
        o = b[k*17:k*17+17]
        v += list(o[:11]) + [o[11]&3, (o[11]>>2)&3, o[12]&7, o[13]&3, (o[13]>>2)&7, o[14], o[15]&1,
                             (o[15]>>1)&31, o[16], (o[12]>>3)&15]
    v += list(b[102:111]) + [b[111]&7, (b[111]>>3)&1]
    v += list(b[112:116]) + [b[116]&1, (b[116]>>1)&7, (b[116]>>4)&7, b[117]] + list(b[118:128])
    return v

def generate():
    bank = json.loads((ROOT/'assets/fm6/trapstation-fm6-bank.json').read_text(encoding='utf-8'))
    out = ROOT/'build/gen/trap_fm6_factory.h'
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = ['/* Generated by tools/gen_trap_fm6.py from assets/fm6/trapstation-fm6-bank.json. */',
             '#define TF6_COUNT 22u',
             'static const uint8_t TF6_PATCH[TF6_COUNT][155] = {']
    for p in bank:
        assert len(p['values']) == 155
        lines.append('{' + ','.join(map(str,p['values'])) + '},')
    lines += ['};','static const uint8_t TF6_PACKED[TF6_COUNT][128] = {']
    for record in bank:
        v=record['values']; b=[]
        for k in range(6):
            o=v[k*21:(k+1)*21]
            b += o[:11]+[o[11]|o[12]<<2, o[13]|o[20]<<3, o[14]|o[15]<<2, o[16], o[17]|o[18]<<1, o[19]]
        b += v[126:135]+[v[135]|v[136]<<3]+v[137:141]+[v[141]|v[142]<<1|v[143]<<4, v[144]]+v[145:155]
        assert len(b)==128
        assert list(unpack(bytes(b)))==v
        lines.append('{'+','.join(map(str,b))+'},')
    lines += ['};','static const uint16_t TF6_FX[TF6_COUNT][3] = {']
    lines += ['{'+','.join(map(str,p['fx']))+'},' for p in bank]
    lines += ['};','static const char *const TF6_NAMES[TF6_COUNT] = {']
    lines += [json.dumps(p['name'])+',' for p in bank]
    lines += ['};','static const char *const TF6_ORIGINAL[TF6_COUNT] = {']
    lines += [json.dumps(p['name'])+',' for p in bank]
    lines += ['};']
    out.write_text('\n'.join(lines)+'\n', encoding='utf-8')

if __name__ == '__main__':
    generate()
