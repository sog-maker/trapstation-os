"""The fonts of the final design "Grid + Heritage" (v0.9.9.3, docs/design):
its SVGs set every text in "Consolas, DejaVu Sans Mono, monospace", weight 600. Consolas may not be embedded in this
GPL firmware; DejaVu Sans Mono Bold (Bitstream Vera / DejaVu licence: free to embed) is the design's own fallback. Set at
0.9 x the design's size it matches Consolas' cap height and advance (Consolas: cap 0.638 em, advance 0.550 em; DejaVu
Sans Mono: 0.729, 0.602). Rasterised by tools/gen_aa_font.py's emitter (4-bit alpha, Huffman), so firmware/src/gfx.c
draws them as the other UI fonts.

  gen_gh_fonts.py OUT.h

Faces (design size -> px):  GS 7/8 -> 7   GM 9 -> 8   GT 10/11 -> 9   GV 12 -> 11   GB 13 -> 12   GH 16..19 -> 16
                            GX 32/43 -> 36 (the big digits: CLOCK's BPM, the track overlay's "T5")
Extras: the dashes and the play triangle (one-byte codes as Windows-1252: 0x96 en dash, 0x97 em dash; 0x86 the
triangle), the German letters of the hints (Latin-1)."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_aa_font as g

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
if not Path(FONT).exists():
    FONT = "/mnt/c/Windows/Fonts/DejaVuSansMono-Bold.ttf"
g.CODE.update({0x2013: 0x96, 0x2014: 0x97, 0x25B6: 0x86})
EXT = [0xC4, 0xD6, 0xDC, 0xDF, 0xE4, 0xF6, 0xFC, 0x2013, 0x2014, 0x25B6, 0x2026]
BIG = "".join(chr(c) for c in range(32, 96)) + "x"
L = lambda s: [ord(c) for c in s[1:]]
FACES = [("GC", FONT, 21, (32, 32), L(" .0123456789"), 0.0, 2),
         ("GS", FONT, 7, (32, 126), EXT, 0.0, 2),
         ("GM", FONT, 8, (32, 126), EXT, 0.0, 2),
         ("GT", FONT, 9, (32, 126), EXT, 0.0, 2),
         ("GV", FONT, 11, (32, 126), [0x2014, 0x2026], 0.0, 2),
         ("GB", FONT, 12, (32, 32), L(BIG), 0.0, 2),
         ("GH", FONT, 16, (32, 32), L(BIG), 0.0, 2),
         ("GX", FONT, 36, (32, 32), L(" .0123456789T"), 0.0, 2)]

def main():
    out = ["/* generated by tools/gen_gh_fonts.py: 4-bit alpha glyphs (DejaVu Sans Mono Bold, Bitstream Vera / DejaVu "
           "licence: free to embed; the design's fallback for Consolas) */", "#pragma once", "#include <stdint.h>", ""]
    g.HUFF[0] = tuple(f[0] for f in FACES)
    total = 0
    for f in FACES:
        text, c = g.emit(f, 0.0, 1.0, 1)
        out.append(text)
        total += c["total"]
        print(f"face {f[0]}: {c['px']}px h{c['h']} base{c['asc']} {c['glyphs']} glyphs = {c['total']} B, digit adv {c['adv_digit']:.2f}px")
    Path(sys.argv[1]).write_text("\n".join(out))
    print(f"gh fonts total {total} B -> {sys.argv[1]}")

if __name__ == "__main__":
    main()
