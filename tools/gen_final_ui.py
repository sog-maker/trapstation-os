def pixel(p):
    r,g,b=p;v=(r>>3)<<11|(g>>2)<<5|(b>>3)
    return v>>8|((v&255)<<8)
def pack(row):
    out=bytearray();i=0
    while i<len(row):
        j=i+1
        while j<len(row) and j-i<128 and row[j]==row[i]:j+=1
        if row[i]==-1:
            out.extend((0,j-i));i=j
        elif j-i>=2:

            j=min(j,i+127);out.append(j-i);out+=row[i].to_bytes(2,'little');i=j
        else:
            a=i;i+=1
            while i<len(row) and i-a<128:
                if row[i]==-1 or (i+1<len(row) and row[i]==row[i+1]):break
                i+=1
            out.append(128+i-a-1)
            for p in row[a:i]:out+=p.to_bytes(2,'little')
    return bytes(out)
rows={};data=bytearray();offset=[];ids=[];indexbytes=0;header=['/* Generated by tools/gen_final_ui.py from approved native masters. */','#pragma once','#include <stdint.h>','typedef struct {uint16_t w,h;const uint16_t *rows;} final_img_t;']
