    ri=[]
    for y in range(im.height):
        row=tuple(-1 if previous and im.getpixel((x,y))==previous.getpixel((x,y)) else pixel(im.getpixel((x,y))) for x in range(im.width))
        if row not in rows:
            rows[row]=len(rows);offset.append(len(data));data+=pack(row)
        ri.append(rows[row])
    ids.append(name)
    encoded=[];i=0
    while i<len(ri):
        j=i+1
        while j<len(ri) and ri[j]==ri[i]:j+=1
        if j-i>2:encoded.extend([32768+j-i-1,ri[i]])
        else:encoded.extend(ri[i:j])
        i=j
    indexbytes+=len(encoded)*2
    header+=['#define WS_'+name+' '+str(len(ids)-1),'static const uint16_t WS_'+name+'_rows[]={'+','.join(map(str,encoded))+'};']
    proof.append({'asset':name,'width':im.width,'height':im.height,'sha256Pixels':hashlib.sha256(im.tobytes()).hexdigest()})

    for y,idx in enumerate(ri):
        p=offset[idx];decoded=[]
        while len(decoded)<im.width:
            tag=data[p];p+=1
            if tag==0:
                n=data[p];p+=1;decoded.extend([-1]*n)
            elif tag&128:
                n=(tag&127)+1
                for j in range(n):decoded.append(int.from_bytes(data[p:p+2],'little'));p+=2
            else:
                n=tag;v=int.from_bytes(data[p:p+2],'little');p+=2;decoded.extend([v]*n)
        assert decoded==[-1 if previous and im.getpixel((x,y))==previous.getpixel((x,y)) else pixel(im.getpixel((x,y))) for x in range(im.width)]
