"""Fixed 44.1 kHz coefficients; no runtime floating-point in Tape/VHS."""
from pathlib import Path
import math
FS=44100
def array(name,kind,values):
    return f'static const {kind} {name}[{len(values)}] = {{'+', '.join(map(str,values))+'};\n'
text='/* Generated by tools/gen_tape_tables.py; do not edit. SPDX-License-Identifier: GPL-3.0-only */\n'
text+=array('TAPE_LP','int32_t',[round((1-math.exp(-2*math.pi*hz/FS))*32768) for hz in (4000,6000,8000,10000,12000,14000,16000)]+[32768])

text+=array('TAPE_HISS','int32_t',[0]+[round(32768*math.sqrt(45)*10**((-70+(i-1)*30/126)/20)) for i in range(1,128)])
text+=f'#define TAPE_WOW_K {round(15*math.log(2)*FS*256*1000/(127*1200*2*math.pi))}u\n'
text+=f'#define TAPE_FLUT_K {round(5*math.log(2)*FS*256*1000/(127*1200*2*math.pi))}u\n'
Path('firmware/src/trap_tape_tables.h').write_text(text)
